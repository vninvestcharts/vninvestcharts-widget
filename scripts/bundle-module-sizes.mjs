// Per-module byte attribution for a tsup bundle, via its sourcemap.
//
// Why not `npm run build:analyze`: tsup in this repo has no --analyze option, so
// that script exits 1 with a CACError. Script existence is not capability, which
// is the same trap as the audit that passed 16/16 scripts by checking only that
// they were listed in package.json.
//
// Usage: node scripts/bundle-module-sizes.mjs [--map dist/index.js.map] [--top 40]
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const getArg = (name, dflt) => {
	const i = args.indexOf(name);
	return i >= 0 && args[i + 1] ? args[i + 1] : dflt;
};

const mapPath = path.resolve(getArg("--map", "dist/index.js.map"));
const top = Number(getArg("--top", "40"));

if (!fs.existsSync(mapPath)) {
	console.log(`no sourcemap at ${mapPath} - run npm run build first`);
	process.exit(1);
}

const map = JSON.parse(fs.readFileSync(mapPath, "utf8"));
const { sources, sourcesContent } = map;

/**
 * Attribute generated bytes to the first non-minified source range that produced
 * them. A segment maps a generated [start,end) span to a source; the length of
 * that span is the cost that source is responsible for in the output.
 */
/** Decode one base64 VLQ segment into its integer fields. */
function decodeVlq(segment) {
	const values = [];
	let shift = 0;
	let value = 0;
	for (const ch of segment) {
		const digit = CHARS.indexOf(ch);
		if (digit === -1) throw new Error(`bad base64 VLQ char ${ch}`);
		const hasContinuation = digit & 32;
		value += (digit & 31) << shift;
		if (hasContinuation) {
			shift += 5;
			continue;
		}
		const negative = value & 1;
		value >>= 1;
		values.push(negative ? (value === 0 ? -0x80000000 : -value) : value);
		value = 0;
		shift = 0;
	}
	return values;
}

const CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

/**
 * Attribute generated bytes to the source that produced them.
 *
 * Two things this has to get right, both of which silently produce garbage rather
 * than an error if you skip them:
 *
 *   1. Source-map fields are base64 VLQ **deltas**, not absolute values. Reading
 *      parts[1] as an absolute index attributes the whole bundle to whichever
 *      module happens to be source 0, which is how this first reported 1156 KB of
 *      "VNInvestCharts.tsx" and 0 KB of legacy lane.
 *   2. Splitting each generated line must be hoisted out of the segment loop.
 *      Per-segment splitting is quadratic and made this hang for five minutes.
 *
 * Attribution is proportional within a line, so treat the numbers as a ranking,
 * not as byte-exact accounting.
 */
const lineStarts = [0];
for (let i = 0; i < map.mappings.length; i += 1) {
	if (map.mappings[i] === ";") lineStarts.push(i + 1);
}
const lineEnd = (line) => lineStarts[line + 1] ?? map.mappings.length + 1;

const bySource = new Map();
let srcIdx = 0;
let srcLine = 0;
let srcCol = 0;

map.mappings.split(";").forEach((line, genLine) => {
	if (!line) return;
	const segments = line.split(",");
	const perSegment = Math.max(1, (lineEnd(genLine) - lineStarts[genLine]) / segments.length);
	for (const segment of segments) {
		if (!segment) continue;
		const f = decodeVlq(segment);
		if (f.length >= 4) {
			srcIdx += f[1];
			srcLine += f[2];
			srcCol += f[3];
			const src = sources[srcIdx];
			if (src) bySource.set(src, (bySource.get(src) ?? 0) + perSegment);
		}
	}
});

// Group into buckets the plan actually cares about.
const LEGACY_ROOTS = [
	"src/lib/core/DynamicChart",
	"src/lib/ChartCanvas",
	"src/lib/GenericChartComponent",
	"src/lib/GenericComponent",
	"src/lib/axes",
	"src/lib/coordinates",
	"src/lib/interactive",
	"src/lib/tooltip",
	"src/lib/annotation",
	"src/lib/scale",
	"src/lib/series",
	"src/lib/core/PaneTooltip",
];
const isLegacy = (s) => LEGACY_ROOTS.some((r) => s.includes(r));
const norm = (s) => s.replace(/^.*?(src\/)/, "$1");

const rows = [...bySource.entries()]
	.map(([src, bytes]) => ({ src: norm(src), bytes: Math.round(bytes) }))
	.sort((a, b) => b.bytes - a.bytes);

const legacyTotal = rows.filter((r) => isLegacy(r.src)).reduce((n, r) => n + r.bytes, 0);
const grand = rows.reduce((n, r) => n + r.bytes, 0);

console.log(`sourcemap: ${path.relative(process.cwd(), mapPath)}`);
console.log(`attributed ${(grand / 1024).toFixed(1)} KB across ${rows.length} modules\n`);
console.log(`LEGACY-LANE modules in this chunk: ${(legacyTotal / 1024).toFixed(1)} KB ` +
	`(${((legacyTotal / grand) * 100).toFixed(1)}% of attributed output)\n`);

const byDir = new Map();
for (const r of rows.filter((x) => isLegacy(x.src))) {
	const d = path.posix.dirname(r.src);
	byDir.set(d, (byDir.get(d) ?? 0) + r.bytes);
}
console.log("legacy by directory:");
for (const [d, b] of [...byDir].sort((a, b) => b[1] - a[1])) {
	console.log(`  ${(b / 1024).toFixed(2).padStart(8)} KB  ${d}`);
}

console.log(`\ntop ${top} modules overall:`);
for (const r of rows.slice(0, top)) {
	console.log(`  ${(r.bytes / 1024).toFixed(2).padStart(8)} KB  ${r.src}`);
}

// Per-module detail for the legacy lane. This is the number a removal plan needs:
// the directory totals hide that most of the cost is two files, and that a third
// of the lane is reachable from the fork registry rather than from DynamicChart.
if (args.includes("--legacy-detail")) {
	const legacy = rows.filter((r) => isLegacy(r.src));
	console.log(`\nlegacy-lane modules present in this chunk: ${legacy.length}, ${(legacyTotal / 1024).toFixed(1)} KB`);
	for (const r of legacy) console.log(`  ${(r.bytes / 1024).toFixed(2).padStart(8)} KB  ${r.src}`);
}